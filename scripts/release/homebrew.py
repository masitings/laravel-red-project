#!/usr/bin/env python3
"""Render the Homebrew formula (command-line tools) and cask (desktop app)
for a release, from the .sha256 files the release workflow produced.

    homebrew.py <tag> <repo> <dist-dir> <tap-dir>

Writes <tap-dir>/Formula/red.rb and, when the disk images are there,
<tap-dir>/Casks/red.rb.
"""
import pathlib
import sys


def sha(dist: pathlib.Path, name: str) -> str | None:
    path = dist / f"{name}.sha256"
    if not path.is_file():
        return None
    return path.read_text().split()[0]


def formula(tag: str, repo: str, dist: pathlib.Path) -> str:
    version = tag.removeprefix("v")
    base = f"https://github.com/{repo}/releases/download/{tag}"

    def block(target: str) -> str:
        name = f"red-{tag}-{target}.tar.gz"
        digest = sha(dist, name)
        if digest is None:
            sys.exit(f"missing {name}.sha256 in {dist}")
        return f'      url "{base}/{name}"\n      sha256 "{digest}"'

    return f'''# Generated by RED Project's release workflow; do not edit by hand.
class Red < Formula
  desc "Local PHP development environment: sites, PHP, services, mail and dumps"
  homepage "https://github.com/{repo}"
  version "{version}"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
{block("aarch64-apple-darwin")}
    end
    on_intel do
{block("x86_64-apple-darwin")}
    end
  end

  on_linux do
    on_intel do
{block("x86_64-unknown-linux-gnu")}
    end
  end

  def install
    bin.install "red", "redd", "red-helper"
  end

  def caveats
    <<~EOS
      Finish the setup (privileged helper, start at login, DNS and HTTPS) with:
        red setup
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/red --version")
  end
end
'''


def cask(tag: str, repo: str, dist: pathlib.Path) -> str | None:
    version = tag.removeprefix("v")
    arm = sha(dist, f"RED-{tag}-macos-aarch64.dmg")
    intel = sha(dist, f"RED-{tag}-macos-x86_64.dmg")
    if arm is None or intel is None:
        return None
    return f'''# Generated by RED Project's release workflow; do not edit by hand.
cask "red" do
  arch arm: "aarch64", intel: "x86_64"

  version "{version}"
  sha256 arm:   "{arm}",
         intel: "{intel}"

  url "https://github.com/{repo}/releases/download/v#{{version}}/RED-v#{{version}}-macos-#{{arch}}.dmg"
  name "RED"
  desc "Local PHP development environment"
  homepage "https://github.com/{repo}"

  auto_updates true
  depends_on macos: ">= :monterey"

  app "RED.app"
  binary "#{{appdir}}/RED.app/Contents/MacOS/red"

  caveats <<~EOS
    Finish the setup (privileged helper, start at login, DNS and HTTPS) with:
      red setup
  EOS
end
'''


def main() -> None:
    tag, repo, dist, tap = sys.argv[1:]
    dist_dir = pathlib.Path(dist)
    tap_dir = pathlib.Path(tap)
    (tap_dir / "Formula").mkdir(parents=True, exist_ok=True)
    (tap_dir / "Formula" / "red.rb").write_text(formula(tag, repo, dist_dir))
    print("wrote Formula/red.rb")
    rendered = cask(tag, repo, dist_dir)
    if rendered:
        (tap_dir / "Casks").mkdir(parents=True, exist_ok=True)
        (tap_dir / "Casks" / "red.rb").write_text(rendered)
        print("wrote Casks/red.rb")


if __name__ == "__main__":
    main()
