//! The dump server: receives `dump()` output from sites and keeps it for
//! the GUI and CLI instead of printing it into the page.
//!
//! Symfony's VarDumper (which Laravel's `dump()` and `dd()` use) has a
//! "server" mode: with `VAR_DUMPER_FORMAT=server` it connects to
//! `VAR_DUMPER_SERVER` (default `127.0.0.1:9912`) and writes one line per
//! dump, the base64 of a PHP-serialised `[Data $data, array $context]`.
//! RED sets both variables for PHP requests while capturing is on.
//!
//! Turning the payload into HTML needs VarDumper itself, so RED hands each
//! payload to a short PHP script that loads the project's own
//! `symfony/var-dumper` (and nothing else from `vendor/`) and renders it
//! with its `HtmlDumper`.

use std::collections::VecDeque;
use std::path::{Path, PathBuf};
use std::process::Stdio;
use std::sync::Mutex;
use std::sync::atomic::{AtomicBool, AtomicU64, Ordering};
use std::time::Duration;

use red_api::{DumpEntry, DumpSource, Event};
use serde::Deserialize;
use tokio::io::{AsyncBufReadExt, AsyncWriteExt, BufReader};
use tokio::net::{TcpListener, TcpStream};
use tokio::process::Command;
use tokio_util::sync::CancellationToken;

/// Dumps kept in memory.
pub const KEEP_DUMPS: usize = 200;
/// Largest payload line accepted.
const MAX_PAYLOAD: usize = 16 * 1024 * 1024;
/// How long rendering one dump may take.
const RENDER_TIMEOUT: Duration = Duration::from_secs(10);

/// The renderer, run as `php render.php <var-dumper dir>` with the payload
/// on stdin. It prints `{"html": ..., "context": ...}`.
const RENDER_SCRIPT: &str = r#"<?php
// Generated by RED Project: renders one VarDumper server payload as HTML.
// Only classes of symfony/var-dumper are loaded, from the directory given.
$dir = $argv[1] ?? '';
spl_autoload_register(static function (string $class) use ($dir): void {
    $prefix = 'Symfony\\Component\\VarDumper\\';
    if (strncmp($class, $prefix, strlen($prefix)) !== 0) {
        return;
    }
    $file = $dir . '/' . str_replace('\\', '/', substr($class, strlen($prefix))) . '.php';
    if (is_file($file)) {
        require $file;
    }
});
$payload = base64_decode((string) stream_get_contents(STDIN), true);
$value = $payload === false ? false : @unserialize($payload);
if (!is_array($value) || !isset($value[0]) || !$value[0] instanceof \Symfony\Component\VarDumper\Cloner\Data) {
    fwrite(STDERR, "not a VarDumper payload\n");
    exit(2);
}
$context = is_array($value[1] ?? null) ? $value[1] : [];
$dumper = new \Symfony\Component\VarDumper\Dumper\HtmlDumper();
$html = $dumper->dump($value[0], true);
$plain = static function ($v) use (&$plain) {
    if (is_array($v)) {
        return array_map($plain, $v);
    }
    return is_scalar($v) || $v === null ? $v : null;
};
echo json_encode(
    ['html' => $html, 'context' => $plain($context)],
    JSON_INVALID_UTF8_SUBSTITUTE | JSON_PARTIAL_OUTPUT_ON_ERROR
);
"#;

#[derive(Debug, Deserialize)]
struct Rendered {
    html: String,
    #[serde(default)]
    context: serde_json::Value,
}

/// Captured dumps plus the capture switch.
#[derive(Debug)]
pub struct Dumps {
    enabled: AtomicBool,
    next_id: AtomicU64,
    entries: Mutex<VecDeque<DumpEntry>>,
    script: PathBuf,
}

impl Dumps {
    pub fn new(data_dir: &Path, enabled: bool) -> Self {
        Self {
            enabled: AtomicBool::new(enabled),
            next_id: AtomicU64::new(1),
            entries: Mutex::new(VecDeque::new()),
            script: data_dir.join("dumps").join("render.php"),
        }
    }

    pub fn enabled(&self) -> bool {
        self.enabled.load(Ordering::Relaxed)
    }

    pub fn set_enabled(&self, enabled: bool) {
        self.enabled.store(enabled, Ordering::Relaxed);
    }

    /// Captured dumps, oldest first.
    pub fn list(&self) -> Vec<DumpEntry> {
        self.entries
            .lock()
            .expect("dumps lock poisoned")
            .iter()
            .cloned()
            .collect()
    }

    pub fn clear(&self) {
        self.entries.lock().expect("dumps lock poisoned").clear();
    }

    fn push(&self, mut entry: DumpEntry) {
        entry.id = self.next_id.fetch_add(1, Ordering::Relaxed);
        let mut entries = self.entries.lock().expect("dumps lock poisoned");
        entries.push_back(entry);
        while entries.len() > KEEP_DUMPS {
            entries.pop_front();
        }
    }

    fn script(&self) -> std::io::Result<&Path> {
        let current = std::fs::read_to_string(&self.script).unwrap_or_default();
        if current != RENDER_SCRIPT {
            if let Some(dir) = self.script.parent() {
                std::fs::create_dir_all(dir)?;
            }
            std::fs::write(&self.script, RENDER_SCRIPT)?;
        }
        Ok(&self.script)
    }
}

/// FastCGI parameters that make VarDumper send dumps to RED.
pub fn fastcgi_params(port: u16) -> [(String, String); 2] {
    [
        ("VAR_DUMPER_FORMAT".into(), "server".into()),
        ("VAR_DUMPER_SERVER".into(), format!("127.0.0.1:{port}")),
    ]
}

/// Bind the dump server on 127.0.0.1.
pub async fn bind(port: u16) -> std::io::Result<(TcpListener, u16)> {
    let listener = TcpListener::bind(("127.0.0.1", port)).await?;
    let port = listener.local_addr()?.port();
    Ok((listener, port))
}

/// What the dump server needs from the rest of the daemon.
#[derive(Debug, Clone)]
pub struct Renderer {
    /// PHP CLI binaries to try, preferred first.
    pub php: Vec<PathBuf>,
    /// Project directories to look in for `symfony/var-dumper` when the
    /// dump does not say where it came from.
    pub projects: Vec<PathBuf>,
}

/// Accept dump connections until cancelled. `renderer` is asked for the
/// current PHP binaries and projects for every dump.
pub async fn serve(
    listener: TcpListener,
    dumps: std::sync::Arc<Dumps>,
    renderer: impl Fn() -> Renderer + Send + Sync + Clone + 'static,
    events: tokio::sync::broadcast::Sender<Event>,
    cancel: CancellationToken,
) {
    loop {
        let (stream, _) = tokio::select! {
            () = cancel.cancelled() => return,
            accepted = listener.accept() => match accepted {
                Ok(accepted) => accepted,
                Err(err) => {
                    tracing::warn!(%err, "dump server accept failed");
                    tokio::time::sleep(Duration::from_millis(100)).await;
                    continue;
                }
            },
        };
        let dumps = dumps.clone();
        let renderer = renderer.clone();
        let events = events.clone();
        let cancel = cancel.clone();
        tokio::spawn(async move {
            tokio::select! {
                () = cancel.cancelled() => {}
                () = connection(stream, &dumps, &renderer, &events) => {}
            }
        });
    }
}

async fn connection(
    stream: TcpStream,
    dumps: &Dumps,
    renderer: &(impl Fn() -> Renderer + Send + Sync),
    events: &tokio::sync::broadcast::Sender<Event>,
) {
    let mut reader = BufReader::new(stream);
    loop {
        let mut line = Vec::new();
        let read = {
            let mut limited = tokio::io::AsyncReadExt::take(&mut reader, MAX_PAYLOAD as u64);
            limited.read_until(b'\n', &mut line).await
        };
        match read {
            Ok(0) | Err(_) => return,
            Ok(_) => {}
        }
        let payload = trim_line(&line);
        if payload.is_empty() {
            continue;
        }
        match render(dumps, &renderer(), payload).await {
            Ok(entry) => {
                dumps.push(entry);
                let _ = events.send(Event::DumpReceived);
            }
            Err(err) => tracing::warn!(%err, "could not render a dump"),
        }
    }
}

fn trim_line(line: &[u8]) -> &[u8] {
    let mut end = line.len();
    while end > 0 && matches!(line[end - 1], b'\n' | b'\r' | b' ') {
        end -= 1;
    }
    &line[..end]
}

async fn render(dumps: &Dumps, renderer: &Renderer, payload: &[u8]) -> Result<DumpEntry, String> {
    use base64::Engine;
    let decoded = base64::engine::general_purpose::STANDARD
        .decode(payload)
        .map_err(|e| format!("invalid base64: {e}"))?;
    let source_file = serialized_string(&decoded, "file");
    let var_dumper = source_file
        .as_deref()
        .and_then(|file| var_dumper_above(Path::new(file)))
        .or_else(|| renderer.projects.iter().find_map(|p| var_dumper_in(p)))
        .ok_or("symfony/var-dumper was not found in the project")?;
    let php = renderer
        .php
        .first()
        .ok_or("no PHP CLI binary found to render the dump")?;
    let script = dumps.script().map_err(|e| e.to_string())?;

    let mut child = Command::new(php)
        .arg("-d")
        .arg("display_errors=stderr")
        .arg("-d")
        .arg("memory_limit=512M")
        .arg(script)
        .arg(&var_dumper)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .kill_on_drop(true)
        .spawn()
        .map_err(|e| format!("cannot run {}: {e}", php.display()))?;
    let mut stdin = child.stdin.take().expect("piped");
    let input = payload.to_vec();
    let writer = tokio::spawn(async move {
        let _ = stdin.write_all(&input).await;
    });
    let output = tokio::time::timeout(RENDER_TIMEOUT, child.wait_with_output())
        .await
        .map_err(|_| "rendering timed out".to_owned())?
        .map_err(|e| e.to_string())?;
    let _ = writer.await;
    if !output.status.success() {
        return Err(format!(
            "renderer failed: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        ));
    }
    let rendered: Rendered =
        serde_json::from_slice(&output.stdout).map_err(|e| format!("renderer output: {e}"))?;
    Ok(entry(rendered))
}

fn entry(rendered: Rendered) -> DumpEntry {
    let context = &rendered.context;
    let received = context
        .get("timestamp")
        .and_then(serde_json::Value::as_f64)
        .map(|t| (t * 1000.0) as u64)
        .unwrap_or_else(|| {
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .map(|d| d.as_millis() as u64)
                .unwrap_or_default()
        });
    let source = context.get("source").and_then(|s| {
        let file = s.get("file")?.as_str()?.to_owned();
        let name = s
            .get("name")
            .and_then(|n| n.as_str())
            .map(str::to_owned)
            .unwrap_or_else(|| {
                Path::new(&file)
                    .file_name()
                    .map(|n| n.to_string_lossy().into_owned())
                    .unwrap_or_default()
            });
        Some(DumpSource {
            line: s
                .get("line")
                .and_then(serde_json::Value::as_u64)
                .map(|l| l as u32),
            file,
            name,
        })
    });
    let origin = context
        .get("request")
        .and_then(|r| {
            let method = r.get("method")?.as_str()?;
            let uri = r.get("uri")?.as_str()?;
            Some(format!("{method} {uri}"))
        })
        .or_else(|| {
            context
                .get("cli")
                .and_then(|c| c.get("command_line"))
                .and_then(|c| c.as_str())
                .map(str::to_owned)
        });
    DumpEntry {
        id: 0,
        received,
        html: rendered.html,
        source,
        origin,
    }
}

/// Find `s:<len>:"<key>";s:<n>:"<value>"` in a PHP-serialised payload and
/// return the value. Used to learn the dump's source file before the
/// payload can be unserialised.
pub fn serialized_string(payload: &[u8], key: &str) -> Option<String> {
    let needle = format!("s:{}:\"{key}\";s:", key.len());
    let start = find(payload, needle.as_bytes())? + needle.len();
    let rest = &payload[start..];
    let colon = rest.iter().position(|&b| b == b':')?;
    let len: usize = std::str::from_utf8(&rest[..colon]).ok()?.parse().ok()?;
    let value = rest.get(colon + 2..colon + 2 + len)?;
    String::from_utf8(value.to_vec()).ok()
}

fn find(haystack: &[u8], needle: &[u8]) -> Option<usize> {
    haystack.windows(needle.len()).position(|w| w == needle)
}

/// `vendor/symfony/var-dumper` in `dir` or any parent of it.
fn var_dumper_above(file: &Path) -> Option<PathBuf> {
    file.ancestors().skip(1).find_map(var_dumper_in)
}

fn var_dumper_in(dir: &Path) -> Option<PathBuf> {
    let candidate = dir.join("vendor/symfony/var-dumper");
    candidate
        .join("Cloner/Data.php")
        .is_file()
        .then_some(candidate)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn finds_serialized_strings() {
        let payload = br#"a:2:{i:0;O:1:"X":0:{}i:1;a:1:{s:6:"source";a:3:{s:4:"name";s:9:"index.php";s:4:"file";s:18:"/srv/app/index.php";s:4:"line";i:3;}}}"#;
        assert_eq!(
            serialized_string(payload, "file").as_deref(),
            Some("/srv/app/index.php")
        );
        assert_eq!(serialized_string(payload, "missing"), None);
    }

    #[test]
    fn builds_entries_from_context() {
        let rendered = Rendered {
            html: "<pre>1</pre>".into(),
            context: serde_json::json!({
                "timestamp": 1_760_000_000.5,
                "source": {"name": "web.php", "file": "/app/routes/web.php", "line": 7},
                "request": {"method": "GET", "uri": "http://blog.test/"}
            }),
        };
        let entry = entry(rendered);
        assert_eq!(entry.received, 1_760_000_000_500);
        let source = entry.source.unwrap();
        assert_eq!(source.line, Some(7));
        assert_eq!(source.name, "web.php");
        assert_eq!(entry.origin.as_deref(), Some("GET http://blog.test/"));
    }

    #[test]
    fn keeps_a_bounded_history() {
        let dir = tempfile::tempdir().unwrap();
        let dumps = Dumps::new(dir.path(), true);
        for _ in 0..KEEP_DUMPS + 5 {
            dumps.push(DumpEntry {
                id: 0,
                received: 0,
                html: String::new(),
                source: None,
                origin: None,
            });
        }
        let list = dumps.list();
        assert_eq!(list.len(), KEEP_DUMPS);
        assert_eq!(list.last().unwrap().id, (KEEP_DUMPS + 5) as u64);
    }
}
